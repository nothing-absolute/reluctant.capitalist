from pydantic import BaseModel, Field
from typing import List, Optional
from datetime import datetime

# NOTE: Requires pydantic package
# pip install pydantic

"""
These schemas define the data structures for the Odysseus Backend.
They ensure that when a raw file is ingested, it is correctly categorized,
routed, and presented to the user in the UI review queue.
"""

class RawInputEvent(BaseModel):
    """Represents a new file dropped into the Central Brain by the Watcher."""
    file_path: str
    source_directory: str # e.g., "Reluctant_Capitalist"
    content: str
    timestamp: datetime = Field(default_factory=datetime.now)

class RAGContext(BaseModel):
    """Represents the historical context pulled from ChromaDB."""
    query_used: str
    retrieved_text: str
    source_files_referenced: List[str]

class GeneratedOutput(BaseModel):
    """Represents one of the potential formats generated by the local LLM."""
    format_type: str # e.g., "YouTube_Script", "Substack_Post", "Short_Hook"
    target_channel: str # e.g., "Channel A (Systems)", "Channel B (Narrative)"
    title: str
    body_content: str
    confidence_score: float # How confident the LLM is that this format fits the input (0.0 - 1.0)

class ReviewQueueItem(BaseModel):
    """
    The master object that populates the Odysseus GUI Inbox.
    It contains the original input, the historical context, and the proposed outputs.
    """
    id: str
    status: str = "PENDING_HUMAN_REVIEW" # PENDING, APPROVED, REJECTED, PIVOTED
    raw_input: RawInputEvent
    rag_context_applied: RAGContext
    proposed_outputs: List[GeneratedOutput]
    
    def approve_output(self, selected_format_index: int):
        """Marks an output as approved, ready to be sent to Runpod/Cloud APIs."""
        self.status = "APPROVED"
        selected = self.proposed_outputs[selected_format_index]
        print(f"Output Approved: {selected.title} for {selected.target_channel}")
        return selected

