import fs from 'node:fs';
import path from 'node:path';
import { splitDoc, serialize, writeFileBackedUp } from './lib/staging.mjs';
import { splitSections, degenerate, preservation } from './lib/quality.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const CONTENT = path.join(ROOT, 'src', 'content');
const API = process.env.POLISH_API ?? 'http://localhost:18000/v1';
const MODEL = process.env.POLISH_MODEL ?? 'qwen14b';
const TIMEOUT = Number(process.env.POLISH_TIMEOUT_MS ?? 900000);
const MAX_TOKENS = Number(process.env.POLISH_MAX_TOKENS ?? 4096);
const argv = process.argv.slice(2);
const apply = argv.includes('--apply');
const retries = Number(process.env.REWRITE_RETRIES ?? 2);
const limit = Number(process.env.REWRITE_LIMIT ?? 0);

const CONTEXT = fs.readFileSync(path.join(ROOT, 'scripts', 'lib', 'creator-context.md'), 'utf8');
const quality = JSON.parse(fs.readFileSync(path.join(ROOT, 'reviews', 'QUALITY.json'), 'utf8'));
const targets = quality.reports.filter((r) => r.narrativeLoop).slice(0, limit || undefined);

const SCHEMA = {
  type: 'object',
  properties: { body: { type: 'string' } },
  required: ['body'],
};

const SYSTEM = `You repair machine-generated drafts for "The Reluctant Capitalist".

${CONTEXT}

## The problem

The text you are given was generated by a smaller model that fell into a repetition loop. It says
the same sentence over and over, often three near-identical variations in a row. The content
underneath is usually fine. The prose is not.

## What to do

Rewrite the narrative into clean, single-voice prose.

- **Keep every fact.** URLs, dollar figures, numbers, names, dates, specifications. Do not
  summarise, compress or drop them. If the original says three prices, keep three prices.
- **Delete the looping.** If the same claim is made three times, keep the best one. If a sentence
  appears more than once, it appears once.
- **Do not invent.** Nothing new. No new facts, no new conclusions, no new claims about the world.
- Preserve the original headings that still make sense. Add headings only where the content clearly
  has distinct parts.
- Preserve any code blocks, tables, and link syntax exactly as given.
- If the original contains a raw transcript, tool log or file listing, leave that part untouched.
  Only rewrite the narrative prose.
- Same voice as the original intent: first person, plain, declarative, unsentimental, no hype,
  no emoji, no "excited to announce".

Return only JSON with a single key "body" containing the repaired Markdown.`;

async function call(user, temperature) {
  const res = await fetch(`${API}/chat/completions`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    signal: AbortSignal.timeout(TIMEOUT),
    body: JSON.stringify({
      model: MODEL,
      messages: [
        { role: 'system', content: SYSTEM },
        { role: 'user', content: user },
      ],
      temperature,
      max_tokens: MAX_TOKENS,
      response_format: { type: 'json_schema', json_schema: { name: 'rewrite', strict: true, schema: SCHEMA } },
    }),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const j = await res.json();
  const c = j?.choices?.[0];
  if (c?.finish_reason === 'length') throw new Error('truncated');
  const text = c?.message?.content ?? '';
  try {
    return JSON.parse(text);
  } catch {
    const m = text.match(/\{[\s\S]*\}/);
    if (m) {
      try {
        return JSON.parse(m[0]);
      } catch {}
    }
    throw new Error('unparseable');
  }
}

const CHUNK_CHARS = Number(process.env.REWRITE_CHUNK_CHARS ?? 5000);

function chunkNarrative(text, limit = CHUNK_CHARS) {
  const blocks = String(text).split(/\n{2,}/);
  const chunks = [];
  let current = '';
  for (const block of blocks) {
    if (current && current.length + block.length + 2 > limit) {
      chunks.push(current);
      current = block;
    } else {
      current = current ? `${current}\n\n${block}` : block;
    }
  }
  if (current.trim()) chunks.push(current);
  return chunks;
}

console.log(`[rewrite] ${targets.length} posts with narrative loops | model=${MODEL} | apply=${apply}`);
const results = { generatedAt: new Date().toISOString(), model: MODEL, applied: apply, rewritten: [], rejected: [], failed: [] };

for (const target of targets) {
  const [section, slug] = target.id.split('/');
  const abs = path.join(CONTENT, section, `${slug}.md`);
  if (!fs.existsSync(abs)) continue;
  const raw = fs.readFileSync(abs, 'utf8');
  const { data, body } = splitDoc(raw);
  const { narrative, raw: rawPart } = splitSections(body);
  const isSynthesis = String(data.source ?? '').startsWith('synthesis://');

  if (isSynthesis) {
    console.log(`  · ${target.id} — synthesis post, regenerating instead`);
    results.rejected.push({ id: target.id, reason: 'synthesis — handled by synthesize-posts.mjs' });
    continue;
  }

  process.stdout.write(`  · ${target.id.slice(0, 62)} ... `);
  const chunks = chunkNarrative(narrative);
  let done = false;
  for (let attempt = 1; attempt <= retries && !done; attempt += 1) {
    const rebuilt = [];
    const chunkErrors = [];
    let passthrough = 0;
    for (let ci = 0; ci < chunks.length; ci += 1) {
      const source = chunks[ci];
      const isFirst = ci === 0;
      const isLast = ci === chunks.length - 1;
      let out;
      try {
        out = await call(
          [
            `TITLE: ${data.title}`,
            `SECTION: ${section}`,
            isFirst ? 'This is part 1 of N. Open the post properly.' : `This is part ${ci + 1} of ${chunks.length}, continuing the same post. Do not re-introduce it.`,
            isLast ? 'This is the final part. Close it properly if the content calls for it.' : 'More follows, so do not add a conclusion.',
            '',
            'TEXT TO REPAIR:',
            source.trim(),
          ].join('\n'),
          0.3 + attempt * 0.15,
        );
      } catch (err) {
        rebuilt.push(source);
        passthrough += 1;
        chunkErrors.push(`chunk ${ci + 1}: ${err.message}`);
        continue;
      }
      const piece = String(out.body ?? '').trim();
      if (!piece) {
        rebuilt.push(source);
        passthrough += 1;
        chunkErrors.push(`chunk ${ci + 1}: empty`);
        continue;
      }
      rebuilt.push(piece);
    }

    if (passthrough === chunks.length) {
      if (attempt === retries) {
        results.failed.push({ id: target.id, error: `all chunks failed: ${chunkErrors.slice(0, 3).join('; ')}` });
        console.log(`FAILED (all chunks returned nothing)`);
      }
      continue;
    }

    const candidate = rebuilt.join('\n\n');
    const gate = degenerate(candidate);
    const keep = preservation(narrative, candidate);
    if (!gate.ok) {
      if (attempt === retries) {
        results.rejected.push({ id: target.id, reason: `still degenerate: ${gate.issues.join('; ')}` });
        console.log(`REJECTED (${gate.issues.join('; ')})`);
      }
      continue;
    }
    if (keep < 0.7) {
      if (attempt === retries) {
        results.rejected.push({ id: target.id, reason: `fact loss ${(keep * 100).toFixed(0)}%` });
        console.log(`REJECTED (fact loss ${(keep * 100).toFixed(0)}%)`);
      }
      continue;
    }

    const nextBody = rawPart.trim() ? `${candidate}\n\n${rawPart.trim()}` : candidate;
    if (apply) {
      writeFileBackedUp(ROOT, abs, serialize(data, nextBody));
    }
    results.rewritten.push({
      id: target.id,
      chunks: chunks.length,
      passthrough,
      words: gate.words,
      attempts: attempt,
      factKeep: Number(keep.toFixed(2)),
    });
    console.log(`ok (${chunks.length} chunk${chunks.length > 1 ? 's' : ''}, ${passthrough} passed through, ${gate.words} words, facts ${(keep * 100).toFixed(0)}%)`);
    done = true;
  }
}

fs.writeFileSync(path.join(ROOT, 'reviews', 'REWRITE.json'), `${JSON.stringify(results, null, 2)}\n`);
console.log(
  `\n[rewrite] ${results.rewritten.length} rewritten, ${results.rejected.length} rejected, ${results.failed.length} failed`,
);
console.log('[rewrite] wrote reviews/REWRITE.json');
